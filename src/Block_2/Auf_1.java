package Block_2;

public class Auf_1 {
    public static void main(String[] args) {
        int summe = 0;

        // Zahlen von 1 - 100 ausgeben
        for(int i = 1; i <= 100; i++) {
            System.out.println(i);

            // Summe um i erhöhen
            summe += i;

        }
        // Summe Ausgeben
        System.out.println(summe);
    }
}
